// Regenerates src/tools/loader.tsx and src/tools/icons.tsx from the tool registry.
// Run after adding or removing a tool:  npm run tools:generate
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const root = path.resolve(import.meta.dirname, "..");
const toolsDir = path.join(root, "src", "tools");
const sources = [path.join(toolsDir, "registry.ts"), ...fs.readdirSync(path.join(toolsDir, "defs")).map((f) => path.join(toolsDir, "defs", f))];

const slugs = [];
const icons = new Set(["wrench"]);
for (const file of sources) {
  const text = fs.readFileSync(file, "utf8");
  for (const m of text.matchAll(/^\s+slug: "([a-z0-9-]+)",\s*$/gm)) slugs.push(m[1]);
  for (const m of text.matchAll(/^\s+icon: "([a-z0-9-]+)",\s*$/gm)) icons.add(m[1]);
}

const duplicates = slugs.filter((s, i) => slugs.indexOf(s) !== i);
if (duplicates.length) throw new Error(`Duplicate tool slugs: ${duplicates.join(", ")}`);
const missing = slugs.filter((s) => !fs.existsSync(path.join(toolsDir, "components", `${s}.tsx`)));
if (missing.length) throw new Error(`Missing components for: ${missing.join(", ")}`);

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const lucide = createRequire(path.join(root, "package.json"))("lucide-react");
const unknown = [...icons].filter((i) => !lucide[pascal(i)]);
if (unknown.length) throw new Error(`Unknown lucide icons: ${unknown.join(", ")}`);

const header = "// Generated by scripts/generate-tools.mjs. Do not edit by hand.\n";

const loader = `"use client";

${header}
/**
 * Maps each tool slug to its lazily-loaded component so every tool ships as its
 * own JavaScript chunk.
 */

import dynamic from "next/dynamic";
import type { ComponentType } from "react";
import { Spinner } from "@/components/tool-ui";
import { useT } from "@/lib/i18n/client";

function loading() {
  return <ToolLoading />;
}

function ToolLoading() {
  const t = useT();
  return (
    <div className="flex min-h-48 items-center justify-center gap-2 text-sm text-muted">
      <Spinner />
      {t("tool.loading")}
    </div>
  );
}

export const TOOL_COMPONENTS: Record<string, ComponentType> = {
${slugs.map((s) => `  "${s}": dynamic(() => import("./components/${s}"), { ssr: false, loading }),`).join("\n")}
};
`;

const sorted = [...icons].sort();
const iconsFile = `${header}
import {
${sorted.map((i) => `  ${pascal(i)},`).join("\n")}
  type LucideIcon,
} from "lucide-react";

/** Explicit map keeps the icon bundle small (no import of the whole icon set). */
const ICONS: Record<string, LucideIcon> = {
${sorted.map((i) => `  "${i}": ${pascal(i)},`).join("\n")}
};

export function ToolIcon({ name, className }: { name: string; className?: string }) {
  const Icon = ICONS[name] ?? Wrench;
  return <Icon className={className} aria-hidden />;
}
`;

fs.writeFileSync(path.join(toolsDir, "loader.tsx"), loader);
fs.writeFileSync(path.join(toolsDir, "icons.tsx"), iconsFile);
console.log(`Generated loader for ${slugs.length} tools and ${icons.size} icons.`);
